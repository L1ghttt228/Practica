using System; 

namespace Task5SortingDelegate 
{
    // объявление делегата: описывает методы сортировки, принимающие массив и не возвращающие значение
    delegate void SortMethod(int[] data);

    class Program
    {
        // метод сортировки пузырьком: соседние элементы сравниваются и меняются местами
        static void BubbleSort(int[] data)
        {
            // внешний цикл for задаёт количество проходов по массиву
            for (int i = 0; i < data.Length - 1; i++)
            {
                // внутренний цикл for сравнивает соседние элементы; - i исключает уже отсортированный конец
                for (int j = 0; j < data.Length - 1 - i; j++)
                {
                    // если левый элемент больше правого, значения меняются местами
                    if (data[j] > data[j + 1])
                    {
                        int temp = data[j]; // temp временно хранит значение первого элемента
                        data[j] = data[j + 1]; // в первый элемент записывается значение второго
                        data[j + 1] = temp; // во второй элемент записывается сохранённое значение
                    }
                }
            }
        }

        // метод быстрой сортировки: запускает рекурсивную сортировку всего массива
        static void QuickSort(int[] data)
        {
            QuickSortPart(data, 0, data.Length - 1); // вызов вспомогательного метода для диапазона от первого до последнего индекса
        }

        // вспомогательный метод сортирует часть массива между индексами left и right
        static void QuickSortPart(int[] data, int left, int right)
        {
            int pivot = data[(left + right) / 2]; // опорный элемент — значение в середине диапазона
            int i = left; // индекс i начинает движение с левого края диапазона
            int j = right; // индекс j начинает движение с правого края диапазона

            // цикл while работает, пока индексы i и j не пересеклись
            while (i <= j)
            {
                while (data[i] < pivot) i++; // оператор ++ сдвигает i вправо, пока элемент меньше опорного
                while (data[j] > pivot) j--; // оператор -- сдвигает j влево, пока элемент больше опорного

                // если индексы не пересеклись, элементы меняются местами
                if (i <= j)
                {
                    int temp = data[i]; // temp временно хранит значение левого элемента
                    data[i] = data[j]; // в левую позицию записывается правый элемент
                    data[j] = temp; // в правую позицию записывается сохранённый левый элемент
                    i++; // сдвиг левого индекса вправо после обмена
                    j--; // сдвиг правого индекса влево после обмена
                }
            }

            if (left < j) QuickSortPart(data, left, j); // рекурсивный вызов: метод сортирует левую часть массива
            if (i < right) QuickSortPart(data, i, right); // рекурсивный вызов: метод сортирует правую часть массива
        }

        // метод выводит элементы массива в одну строку
        static void PrintArray(int[] data)
        {
            foreach (int value in data) // цикл foreach перебирает каждый элемент массива
            {
                Console.Write(value + " "); 
            }

            Console.WriteLine(); 
        }

        static void Main(string[] args)
        {
            int[] data1 = { 5, 2, 9, 1, 7 }; // создание и инициализация первого массива чисел
            int[] data2 = { 5, 2, 9, 1, 7 }; // второй массив с теми же данными для сравнения методов сортировки

            SortMethod sort = BubbleSort; // привязка делегата к методу сортировки пузырьком

            sort(data1); 
            Console.Write("Сортировка пузырьком: "); 
            PrintArray(data1); 

            sort = QuickSort; // перепривязка делегата к методу быстрой сортировки — метод выбирается динамически

            sort(data2); 
            Console.Write("Быстрая сортировка: "); 
            PrintArray(data2); 

            Console.ReadKey(); 
        }
    }
}